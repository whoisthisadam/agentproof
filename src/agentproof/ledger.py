"""The ledger (tasks/README.md) is generated from task front matter. Nobody edits it by hand."""

from __future__ import annotations

from pathlib import Path

from agentproof.tasks import Task, discover, tasks_dir

HEADER = """# Task ledger

Generated by `agentproof ledger` from each task's front matter. Do not edit by hand.
Newest first. Statuses: draft, ready, in-progress, blocked, done, failed, cancelled.

| Task | Title | Product | Tier | Status | Updated |
|---|---|---|---|---|---|
"""


def _cell(value: object) -> str:
    return str(value if value is not None else "").replace("|", "\\|").replace("\n", " ").strip()


def render(root: Path, tasks: list[Task] | None = None) -> str:
    tasks = discover(root) if tasks is None else tasks
    base = tasks_dir(root)
    rows = []
    for task in sorted(tasks, key=lambda t: t.id, reverse=True):
        meta = task.meta or {}
        rel = task.path.relative_to(base).as_posix()
        rows.append(
            f"| [{_cell(task.id)}]({rel}) | {_cell(meta.get('title'))} | {_cell(meta.get('product'))} | "
            f"{_cell(meta.get('tier'))} | {_cell(meta.get('status') or 'INVALID')} | {_cell(meta.get('updated'))} |"
        )
    return HEADER + "\n".join(rows) + ("\n" if rows else "")


def ledger_path(root: Path) -> Path:
    return tasks_dir(root) / "README.md"


def write(root: Path) -> Path:
    path = ledger_path(root)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(root), encoding="utf-8")
    return path


def is_current(root: Path) -> bool:
    path = ledger_path(root)
    if not path.is_file():
        return not discover(root)
    return path.read_text(encoding="utf-8").replace("\r\n", "\n") == render(root)
